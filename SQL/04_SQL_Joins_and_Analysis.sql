/*8.Gender-wise Churn Analysis
Find the total number of churned customers for each gender.*/
with cte as(
select a.gender, count(*) as Number_of_churned_customers 
from customers a join billing as b on a.customerid=b.customerid where b.churn='yes'
group by a.gender)
select * from cte;

/*9. Senior Citizen Analysis
Find the total number of customers and churned customers based on SeniorCitizen status.*/
select a.seniorcitizen, count(*) as total_customers,
sum(case when b.churn='yes' then 1 else 0 end) as churned_customers
from customers as a join billing as b on a.customerid=b.customerid
group by SeniorCitizen;

/*10. Partner and Dependents Analysis
Find the number of customers with and without partners and their total revenue.*/
select a.partner, count(*) as total_number_of_customers, round(sum(b.totalcharges),2) as totalrevenue
from customers as a join billing as b on a.customerid=b.customerid 
