from customers as a join services as b on a.CustomerID=b.CustomerID
join billing as c on a.CustomerID=c.CustomerID 
where c.MonthlyCharges>80;

/*19. Churn Rate by Internet Service
Calculate the churn rate for each InternetService type.*/
SELECT
    a.InternetService,
    COUNT(*) AS Total_Customers,
    SUM(CASE
        WHEN b.Churn = 'Yes' THEN 1
        ELSE 0
    END) AS Churned_Customers,
    ROUND(
        SUM(CASE
            WHEN b.Churn = 'Yes' THEN 1
            ELSE 0
        END) * 100.0 / COUNT(*), 2
    ) AS Churn_Rate
FROM services AS a
JOIN billing AS b
    ON a.CustomerID = b.CustomerID
GROUP BY a.InternetService;

/*20. Customer Service Analysis
Find customers who have both OnlineSecurity and TechSupport, along with their Contract, MonthlyCharges, and Churn status.*/
