from customers as a join billing as b on a.customerid=b.customerid;

/*Internet Service vs Churn
Analyze the number of churned customers for each internet service type.*/
select churn,count(a.churn) Churn, b.InternetService from
billing as a join services as b on a.customerid=b.customerid where churn='yes'
group by InternetService, churn;

/*Revenue by Gender
Calculate the total revenue generated by male and female customers.*/
select b.gender, round(sum(a.Totalcharges),2) Total_Revenue
from billing a join customers b on a.customerid=b.customerid 
group by gender;

