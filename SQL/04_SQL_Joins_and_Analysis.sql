    a.CustomerID,
    a.OnlineSecurity,
    a.TechSupport,
    b.Contract,
    b.MonthlyCharges,
    b.Churn
FROM services AS a
JOIN billing AS b
    ON a.CustomerID = b.CustomerID
WHERE a.OnlineSecurity = 'Yes'
AND a.TechSupport = 'Yes';